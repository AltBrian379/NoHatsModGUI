"""Writing nhcustom2 config files, and reading back the ones this program wrote.

Syntax reference: https://pevhs.ch/tf2/nhcustom2/
Every pattern is written quoted, where the regex is taken as-is except that
a literal quote is doubled. Hats are matched exactly with ^...$, which is
also the author's documented workaround for edge-case bugs.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from .database import Hat, Section

HEADER = "# Generated by NoHatsModGUI. Saving from the app overwrites this file."
KEEP, REMOVE = "keep", "remove"

_ERE_SPECIAL = set("\\.[](){}*+?|^$")


def escape_regex(text: str) -> str:
    """Escape POSIX extended regex metacharacters so text matches literally."""
    return "".join("\\" + c if c in _ERE_SPECIAL else c for c in text)


def quote(pattern: str) -> str:
    return '"' + pattern.replace('"', '""') + '"'


def exact(text: str) -> str:
    """A quoted pattern matching exactly this value."""
    return quote("^" + escape_regex(text) + "$")


def generate(mode: str, sections: list[Section], selected: set[int], all_hats: list[Hat]) -> str:
    """Build config text selecting the hats whose ids are in `selected`."""
    if mode not in (KEEP, REMOVE):
        raise ValueError(f"mode must be {KEEP!r} or {REMOVE!r}")

    name_counts: dict[str, int] = {}
    for hat in all_hats:
        name_counts[hat.name] = name_counts.get(hat.name, 0) + 1

    lines = [HEADER, mode, ""]
    for section in sections:
        hats = section.hats
        chosen = [h for h in hats if h.id in selected]
        if not chosen:
            continue
        lines.append(f"# {section.title}")
        if section.kind == "update" and len(chosen) == len(hats):
            lines.append(f"update:{exact(section.update)}")
        else:
            for hat in chosen:
                lines.append(_hat_line(hat, name_counts, selected, all_hats))
        lines.append("")
    return "\n".join(lines)


def _hat_line(hat: Hat, name_counts: dict[str, int], selected: set[int], all_hats: list[Hat]) -> str:
    line = f"hat:{exact(hat.name)}"
    if name_counts[hat.name] > 1:
        namesakes = [h for h in all_hats if h.name == hat.name]
        if not all(h.id in selected for h in namesakes):
            # Several hats share this name; narrow down to this one's path.
            line += f"}}path:{exact(hat.path)}"
    return line


@dataclass
class SavedSelection:
    mode: str = KEEP
    updates: set[str] = field(default_factory=set)
    hats: list[tuple[str, str | None]] = field(default_factory=list)  # (name, path or None)

    def resolve(self, all_hats: list[Hat]) -> set[int]:
        by_name: dict[str, list[Hat]] = {}
        for hat in all_hats:
            by_name.setdefault(hat.name, []).append(hat)
        ids = {h.id for h in all_hats if h.update in self.updates}
        for name, path in self.hats:
            for hat in by_name.get(name, []):
                if path is None or hat.path == path:
                    ids.add(hat.id)
        return ids


def is_generated(text: str) -> bool:
    return text.lstrip("﻿").startswith(HEADER)


_QUOTED = r'"((?:[^"]|"")*)"'
_UPDATE_LINE = re.compile(rf"^update:{_QUOTED}$")
_HAT_LINE = re.compile(rf"^hat:{_QUOTED}(?:\}}path:{_QUOTED})?$")


def _unexact(quoted_body: str) -> str | None:
    pattern = quoted_body.replace('""', '"')
    if not (pattern.startswith("^") and pattern.endswith("$")):
        return None
    return re.sub(r"\\(.)", r"\1", pattern[1:-1])


def parse_generated(text: str) -> SavedSelection:
    """Read back a config written by generate(). Other lines are ignored."""
    saved = SavedSelection()
    for raw in text.splitlines():
        line = raw.strip()
        if line in (KEEP, REMOVE):
            saved.mode = line
        elif m := _UPDATE_LINE.match(line):
            if (update := _unexact(m.group(1))) is not None:
                saved.updates.add(update)
        elif m := _HAT_LINE.match(line):
            name = _unexact(m.group(1))
            path = _unexact(m.group(2)) if m.group(2) is not None else None
            if name is not None:
                saved.hats.append((name, path))
    return saved
